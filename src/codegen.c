/*
 * Mako Compiler - Code Generator Implementation
 *
 * Transpiles the Mako AST to C source code, which is then compiled
 * by the system's C compiler into a native binary.
 */

#include "codegen.h"
#include <stdarg.h>

/* ── Helpers ─────────────────────────────────────────────────────────── */

static void emit(CodeGen *cg, const char *fmt, ...) {
    va_list args;
    va_start(args, fmt);
    vfprintf(cg->output, fmt, args);
    va_end(args);
}

static void emit_indent(CodeGen *cg) {
    for (int i = 0; i < cg->indent_level; i++) {
        fprintf(cg->output, "    ");
    }
}

static void emit_line(CodeGen *cg, const char *fmt, ...) {
    emit_indent(cg);
    va_list args;
    va_start(args, fmt);
    vfprintf(cg->output, fmt, args);
    va_end(args);
    fprintf(cg->output, "\n");
}

/* ── Forward Declaration ─────────────────────────────────────────────── */
static void gen_node(CodeGen *cg, ASTNode *node);
static void gen_expr(CodeGen *cg, ASTNode *node);

/* ── Expression Code Generation ──────────────────────────────────────── */

static void gen_expr(CodeGen *cg, ASTNode *node) {
    if (!node) return;

    switch (node->type) {
        case NODE_INT_LITERAL:
            emit(cg, "%s", node->value);
            break;

        case NODE_STRING_LITERAL:
            emit(cg, "\"%s\"", node->value);
            break;

        case NODE_BOOL_LITERAL:
            emit(cg, "%s", strcmp(node->value, "true") == 0 ? "1" : "0");
            break;

        case NODE_IDENTIFIER:
            emit(cg, "%s", node->value);
            break;

        case NODE_BINARY_OP:
            emit(cg, "(");
            gen_expr(cg, node->children[0]);
            emit(cg, " %s ", node->op);
            gen_expr(cg, node->children[1]);
            emit(cg, ")");
            break;

        case NODE_UNARY_OP:
            emit(cg, "(%s", node->op);
            gen_expr(cg, node->children[0]);
            emit(cg, ")");
            break;

        case NODE_FN_CALL:
            // Map Mako built-in function names to C equivalents if needed
            emit(cg, "%s(", node->value);
            for (int i = 0; i < node->child_count; i++) {
                if (i > 0) emit(cg, ", ");
                gen_expr(cg, node->children[i]);
            }
            emit(cg, ")");
            break;

        default:
            fprintf(stderr, "CodeGen: unexpected expression node type %d\n", node->type);
            cg->had_error = 1;
            break;
    }
}

/* ── Statement Code Generation ───────────────────────────────────────── */

static void gen_node(CodeGen *cg, ASTNode *node) {
    if (!node) return;

    switch (node->type) {
        case NODE_PROGRAM:
            // Emit C preamble
            emit(cg, "/* Generated by the Mako Compiler */\n");
            emit(cg, "#include <stdio.h>\n");
            emit(cg, "#include <stdlib.h>\n\n");

            // First pass: emit function declarations (forward decls)
            for (int i = 0; i < node->child_count; i++) {
                if (node->children[i]->type == NODE_FN_DECL) {
                    ASTNode *fn = node->children[i];
                    emit(cg, "long long %s(", fn->value);
                    for (int j = 0; j < fn->param_count; j++) {
                        if (j > 0) emit(cg, ", ");
                        emit(cg, "long long %s", fn->params[j]);
                    }
                    emit(cg, ");\n");
                }
            }
            emit(cg, "\n");

            // Second pass: emit function definitions
            for (int i = 0; i < node->child_count; i++) {
                if (node->children[i]->type == NODE_FN_DECL) {
                    gen_node(cg, node->children[i]);
                    emit(cg, "\n");
                }
            }

            // Main function wrapping top-level statements
            emit(cg, "int main(void) {\n");
            cg->indent_level = 1;
            for (int i = 0; i < node->child_count; i++) {
                if (node->children[i]->type != NODE_FN_DECL) {
                    gen_node(cg, node->children[i]);
                }
            }
            emit_line(cg, "return 0;");
            cg->indent_level = 0;
            emit(cg, "}\n");
            break;

        case NODE_VAR_DECL:
            emit_indent(cg);
            emit(cg, "long long %s = ", node->value);
            gen_expr(cg, node->children[0]);
            emit(cg, ";\n");
            break;

        case NODE_ASSIGNMENT:
            emit_indent(cg);
            emit(cg, "%s = ", node->value);
            gen_expr(cg, node->children[0]);
            emit(cg, ";\n");
            break;

        case NODE_PRINT: {
            emit_indent(cg);
            ASTNode *arg = node->children[0];
            if (arg->type == NODE_STRING_LITERAL) {
                emit(cg, "printf(\"%%s\\n\", \"%s\");\n", arg->value);
            } else {
                emit(cg, "printf(\"%%lld\\n\", (long long)(");
                gen_expr(cg, arg);
                emit(cg, "));\n");
            }
            break;
        }

        case NODE_IF:
            emit_indent(cg);
            emit(cg, "if (");
            gen_expr(cg, node->children[0]);
            emit(cg, ") {\n");
            cg->indent_level++;
            // then-block body
            if (node->children[1]) {
                for (int i = 0; i < node->children[1]->child_count; i++) {
                    gen_node(cg, node->children[1]->children[i]);
                }
            }
            cg->indent_level--;
            emit_indent(cg);
            emit(cg, "}");
            if (node->child_count > 2 && node->children[2]) {
                emit(cg, " else {\n");
                cg->indent_level++;
                for (int i = 0; i < node->children[2]->child_count; i++) {
                    gen_node(cg, node->children[2]->children[i]);
                }
                cg->indent_level--;
                emit_indent(cg);
                emit(cg, "}");
            }
            emit(cg, "\n");
            break;

        case NODE_WHILE:
            emit_indent(cg);
            emit(cg, "while (");
            gen_expr(cg, node->children[0]);
            emit(cg, ") {\n");
            cg->indent_level++;
            if (node->children[1]) {
                for (int i = 0; i < node->children[1]->child_count; i++) {
                    gen_node(cg, node->children[1]->children[i]);
                }
            }
            cg->indent_level--;
            emit_indent(cg);
            emit(cg, "}\n");
            break;

        case NODE_BLOCK:
            for (int i = 0; i < node->child_count; i++) {
                gen_node(cg, node->children[i]);
            }
            break;

        case NODE_FN_DECL:
            emit(cg, "long long %s(", node->value);
            for (int i = 0; i < node->param_count; i++) {
                if (i > 0) emit(cg, ", ");
                emit(cg, "long long %s", node->params[i]);
            }
            emit(cg, ") {\n");
            cg->indent_level++;
            if (node->child_count > 0) {
                for (int i = 0; i < node->children[0]->child_count; i++) {
                    gen_node(cg, node->children[0]->children[i]);
                }
            }
            cg->indent_level--;
            emit(cg, "}\n");
            break;

        case NODE_RETURN:
            emit_indent(cg);
            emit(cg, "return ");
            if (node->child_count > 0) gen_expr(cg, node->children[0]);
            else emit(cg, "0");
            emit(cg, ";\n");
            break;

        case NODE_EXPR_STMT:
            emit_indent(cg);
            gen_expr(cg, node->children[0]);
            emit(cg, ";\n");
            break;

        default:
            fprintf(stderr, "CodeGen: unexpected statement node type %d\n", node->type);
            cg->had_error = 1;
            break;
    }
}

/* ── Public API ──────────────────────────────────────────────────────── */

void codegen_init(CodeGen *cg, FILE *output) {
    cg->output = output;
    cg->indent_level = 0;
    cg->had_error = 0;
    cg->error_msg[0] = '\0';
}

int codegen_generate(CodeGen *cg, ASTNode *ast) {
    gen_node(cg, ast);
    return !cg->had_error;
}
